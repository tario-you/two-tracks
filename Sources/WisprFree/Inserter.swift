import AppKit
import ApplicationServices
import CoreAudio

/// Puts text where the cursor is, the way Wispr Flow does: on the clipboard, then ⌘V, then the clipboard as it was.
/// The clipboard entry is marked transient so clipboard managers skip it.
enum Inserter {
  struct Target {
    var app: NSRunningApplication?
    var bundleID: String
    var appName: String
    var windowTitle: String
    var before: String?     // text before the cursor in the focused field, when the app shares it
    var selected: String?
    var editable: Bool
  }

  static var trusted: Bool { AXIsProcessTrusted() }

  @discardableResult
  static func askTrust() -> Bool {
    AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
  }

  /// The app and text field about to receive the words.
  static func target() -> Target {
    let app = NSWorkspace.shared.frontmostApplication
    var t = Target(app: app, bundleID: app?.bundleIdentifier ?? "", appName: app?.localizedName ?? "", windowTitle: "",
                   before: nil, selected: nil, editable: false)
    guard trusted, let pid = app?.processIdentifier else { return t }
    let appEl = AXUIElementCreateApplication(pid)
    AXUIElementSetMessagingTimeout(appEl, 0.15)
    // Chromium and Electron apps share their text only once asked.
    if enhanced.insert(pid).inserted { AXUIElementSetAttributeValue(appEl, "AXManualAccessibility" as CFString, kCFBooleanTrue) }
    if let win: AXUIElement = attr(appEl, kAXFocusedWindowAttribute) { t.windowTitle = attr(win, kAXTitleAttribute) ?? "" }
    guard let el: AXUIElement = attr(appEl, kAXFocusedUIElementAttribute) else { return t }
    var settable = DarwinBoolean(false)
    AXUIElementIsAttributeSettable(el, kAXValueAttribute as CFString, &settable)
    let role: String = attr(el, kAXRoleAttribute) ?? ""
    t.editable = settable.boolValue || ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField", "AXWebArea"].contains(role)
    t.selected = attr(el, kAXSelectedTextAttribute)
    if let value: String = attr(el, kAXValueAttribute), let rangeRef: AXValue = attr(el, kAXSelectedTextRangeAttribute) {
      var range = CFRange()
      if AXValueGetValue(rangeRef, .cfRange, &range) {
        let ns = value as NSString
        let end = min(max(0, range.location), ns.length)
        let start = max(0, end - 400)
        t.before = ns.substring(with: NSRange(location: start, length: end - start))
      }
    }
    return t
  }

  private static var enhanced = Set<pid_t>()

  private static func attr<T>(_ el: AXUIElement, _ name: String) -> T? {
    var v: CFTypeRef?
    guard AXUIElementCopyAttributeValue(el, name as CFString, &v) == .success, let v else { return nil }
    return v as? T
  }

  /// Joins dictated text onto what is already there: a space after a word, none after a space or line break.
  static func joined(_ text: String, after before: String?) -> String {
    guard let last = before?.last, !last.isWhitespace, let first = text.first, !first.isPunctuation || "([{\"'“‘".contains(first) else { return text }
    let han = { (c: Character) in c.unicodeScalars.contains { (0x3000...0x9FFF).contains($0.value) || (0xFF00...0xFFEF).contains($0.value) } }
    if han(last) || han(first) { return text }
    return " " + text
  }

  /// Pastes text into the frontmost app and puts the clipboard back afterwards.
  static func paste(_ text: String) {
    let pb = NSPasteboard.general
    let saved: [[NSPasteboard.PasteboardType: Data]] = (pb.pasteboardItems ?? []).map { item in
      var d: [NSPasteboard.PasteboardType: Data] = [:]
      for type in item.types { if let v = item.data(forType: type) { d[type] = v } }
      return d
    }
    pb.clearContents()
    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    pb.writeObjects([item])
    let mine = pb.changeCount
    keystroke(9, .maskCommand) // ⌘V
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
      guard pb.changeCount == mine else { return }
      pb.clearContents()
      guard !saved.isEmpty else { return }
      pb.writeObjects(saved.map { d in
        let it = NSPasteboardItem()
        for (type, v) in d { it.setData(v, forType: type) }
        return it
      })
    }
  }

  /// Puts text on the clipboard to stay (Copy last transcript).
  static func copy(_ text: String) {
    NSPasteboard.general.clearContents()
    NSPasteboard.general.setString(text, forType: .string)
  }

  static func keystroke(_ key: CGKeyCode, _ flags: CGEventFlags) {
    let src = CGEventSource(stateID: .combinedSessionState)
    let down = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true)
    let up = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false)
    down?.flags = flags
    up?.flags = flags
    down?.post(tap: .cghidEventTap)
    up?.post(tap: .cghidEventTap)
  }
}

/// Mutes the Mac's output while dictating and puts it back after, as Wispr Flow's "mute audio while dictating" does.
/// A marker file records that WisprFree did the muting, so a crash mid-dictation is undone at the next launch.
enum OutputMute {
  private static var mutedByUs = false
  private static let marker = Library.home.appendingPathComponent(".muted-by-wisprfree")

  private static func device() -> AudioObjectID? {
    var id = AudioObjectID(kAudioObjectUnknown)
    var size = UInt32(MemoryLayout<AudioObjectID>.size)
    var a = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultOutputDevice, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    guard AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &a, 0, nil, &size, &id) == noErr, id != kAudioObjectUnknown else { return nil }
    return id
  }

  private static func muted(_ dev: AudioObjectID) -> Bool? {
    var v: UInt32 = 0
    var size = UInt32(MemoryLayout<UInt32>.size)
    var a = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyMute, mScope: kAudioDevicePropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
    guard AudioObjectGetPropertyData(dev, &a, 0, nil, &size, &v) == noErr else { return nil }
    return v != 0
  }

  private static func set(_ dev: AudioObjectID, _ on: Bool) {
    var v: UInt32 = on ? 1 : 0
    var a = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyMute, mScope: kAudioDevicePropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
    AudioObjectSetPropertyData(dev, &a, 0, nil, UInt32(MemoryLayout<UInt32>.size), &v)
  }

  static func mute() {
    guard !mutedByUs, let dev = device(), muted(dev) == false else { return }
    set(dev, true)
    mutedByUs = true
    FileManager.default.createFile(atPath: marker.path, contents: Data())
  }

  static func restore() {
    guard mutedByUs || FileManager.default.fileExists(atPath: marker.path) else { return }
    if let dev = device() { set(dev, false) }
    mutedByUs = false
    try? FileManager.default.removeItem(at: marker)
  }
}
